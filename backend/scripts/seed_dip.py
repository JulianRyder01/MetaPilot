    manifest = {
        "formatVersion": COURSE_META["formatVersion"],
        "id": COURSE_META["id"],
        "name": COURSE_META["name"],
        "author": COURSE_META["author"],
        "version": COURSE_META["version"],
        "description": COURSE_META["description"],
        "library": COURSE_META["library"],
        "collections": COURSE_META["collections"],
    }
    manifest_path = COURSE_DIR / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[1/2] 已生成课程包清单: {manifest_path}")

    # 2) 导入本地数据
    store = LibraryStore(DATA_DIR)
    importer = CourseImporter(store, DATA_DIR / "assets" / "courses")
    assets = {
        p.name: p.read_bytes()
        for p in INTERACTIVES_DIR.glob("*.html")
    }
    result = importer.import_package(manifest, assets)
    print(f"[2/2] 已导入课程: {result}")
    print("     可在客户端「我的库 → 数字图像处理」中开始学习。")
    return True


